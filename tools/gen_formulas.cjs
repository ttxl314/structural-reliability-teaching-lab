/* Generate offline formula SVGs: tools/formulas.json -> src/js/formulas.js
 * Run: node tools/gen_formulas.cjs
 * Requires: _tmp/mathjax/node_modules/mathjax-full (build-time only, not needed at runtime)
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const mjRoot = path.join(root, '_tmp', 'mathjax');
const { createRequire } = require('module');
const req = createRequire(path.join(mjRoot, 'package.json'));

const { mathjax } = req('mathjax-full/js/mathjax.js');
const { TeX } = req('mathjax-full/js/input/tex.js');
const { SVG } = req('mathjax-full/js/output/svg.js');
const { liteAdaptor } = req('mathjax-full/js/adaptors/liteAdaptor.js');
const { RegisterHTMLHandler } = req('mathjax-full/js/handlers/html.js');
const { AllPackages } = req('mathjax-full/js/input/tex/AllPackages.js');

const adaptor = liteAdaptor();
RegisterHTMLHandler(adaptor);

const tex = new TeX({ packages: AllPackages });
const svg = new SVG({ fontCache: 'local' });
const doc = mathjax.document('', { InputJax: tex, OutputJax: svg });

const defs = JSON.parse(fs.readFileSync(path.join(__dirname, 'formulas.json'), 'utf8'));
const out = {};
for (const { id, tex: t } of defs) {
  const node = doc.convert(t, { display: true, em: 16, ex: 8, containerWidth: 1400 });
  let html = adaptor.outerHTML(node);
  // Strip MathJax role/aria wrappers, keep the viewBox and paths
  html = html.replace(/\srole="img"/g, '');
  out[id] = html;
  console.log(id, html.length);
}

const js = '/* Generated by tools/gen_formulas.cjs; do not edit by hand. */\n' +
  'window.RL_FORMULAS = ' + JSON.stringify(out, null, 0) + ';\n';
fs.writeFileSync(path.join(root, 'src', 'js', 'formulas.js'), js);
console.log('wrote src/js/formulas.js', js.length, 'bytes');
